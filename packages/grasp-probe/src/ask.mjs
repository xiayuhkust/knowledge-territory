/**
 * ask —— 「提取练习」提问器的 prompt 本体(和 judge.mjs 平行,是可替换的"技能"件)。
 *
 * 触发那一刻,拿"最近这段 AI 替用户做了什么"生成**一个问题 + 它的总结答案**。
 * 交互是闪卡式(节奏工具,不是考试):先给问题逼用户在脑子里回忆,再(可选)翻开 AI 的总结答案对照。
 * 用户不作答、不发消息——纯旁路反思,不推进主对话。所以"自查"本身不会变成"继续前进"。
 *
 * 为什么提取练习而非再读:回忆/复述才逼出真理解,再读一眼只喂了流畅性错觉(Bjork)。
 * 为什么一次一问:这是"停下来核对一个点"的最小单元;答案是那张闪卡的背面。
 */

export const ASK_INSTRUCTION = `你在帮一个用户对抗"自动化自满":他一直在放行 AI 的产出,可能并没有真的消化。下面是 AI 最近替他做的几件事。

请产出**一个问题 + 它的参考答案**,帮他停下来核对自己是否真懂了其中**最关键、最容易想当然**的那一点。要求:
- 问题能靠**回忆 / 复述 / 解释**来检验(提取练习),而不是再扫一眼原文就能蒙对;**具体**,指向某个真实的改动或决策;口吻平和,像同事随口一问,不是考试。
- 参考答案:两三句话,点破这个问题的关键——AI 当时到底怎么做的 / 该注意什么,让他能拿来对照自己的回忆。
- 严格按下面格式输出,**不要任何其它文字**:
问题：<一个问题>
答案：<两三句话的参考答案>`

/** recentGists: 自上次用户重新入环以来 AI 各跨度做了什么的简述数组。 */
export function buildAskPrompt(recentGists = []) {
  const items = recentGists.length
    ? recentGists.map((g) => `- ${String(g).replace(/\s+/g, ' ').slice(0, 160)}`).join('\n')
    : '- (最近 AI 做了若干自主推进)'
  return `${ASK_INSTRUCTION}\n\nAI 最近替他做的事:\n${items}`
}
